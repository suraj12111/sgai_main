window.switchLanguage = function(lang) {
  localStorage.setItem('sgai_lang', lang);
  
  // Sync dropdown selector value
  const select = document.getElementById('lang-selector');
  if (select) select.value = lang;
  
  const translations = window.TRANSLATIONS[lang];
  if (!translations) return;
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translatedText = translations[key];
    if (translatedText) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translatedText;
      } else {
        // Safe replacement: replace text nodes to preserve inline SVG icons
        let hasTextNode = false;
        el.childNodes.forEach(child => {
          if (child.nodeType === Node.TEXT_NODE && child.nodeValue.trim() !== '') {
            child.nodeValue = translatedText;
            hasTextNode = true;
          }
        });
        if (!hasTextNode && el.children.length === 0) {
          el.textContent = translatedText;
        }
      }
    }
  });
};

// Initialize localization on load
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('sgai_lang') || 'en';
  window.switchLanguage(savedLang);
});
